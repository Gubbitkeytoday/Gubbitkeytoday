const glyph = (ch) => G[ch] ?? G['?'];
export const glyphWidth = (ch) => glyph(ch)[0].length;

/** Width in px of `str` at `scale` (1 px gap between glyphs). */
export function measure(str, scale = 1, gap = 1) {
  const chars = [...str];
  if (!chars.length) return 0;
  return (chars.reduce((w, ch) => w + glyphWidth(ch) + gap, 0) - gap) * scale;
}

/** Path data for `str`, top-left at (x, y). Runs of pixels in a row merge into one rect. */
export function textPath(str, x, y, scale = 1, gap = 1) {
  let d = '';
  let cx = 0;
  for (const ch of str) {
    const rows = glyph(ch);
    rows.forEach((row, ry) => {
      let run = 0;
      for (let rx = 0; rx <= row.length; rx++) {
        if (row[rx] === '#') { run++; continue; }
        if (run) {
          const px = x + (cx + rx - run) * scale;
          const py = y + ry * scale;
          d += `M${r(px)} ${r(py)}h${r(run * scale)}v${r(scale)}h${r(-run * scale)}z`;
          run = 0;
        }
      }
    });
    cx += rows[0].length + gap;
  }
  return d;
}

const r = (n) => Math.round(n * 100) / 100;

/**
 * Pixel text as SVG. `shadow` draws a hard drop shadow; `outline` traces the
 * glyphs one pixel wide on every side so light text stays readable on busy skies.
 */
export function pixelText(str, { x = 0, y = 0, scale = 2, fill = '#000', shadow, shadowOffset, outline, anchor = 'start', cls = '', gap = 1 } = {}) {
  const w = measure(str, scale, gap);
  const left = anchor === 'middle' ? x - w / 2 : anchor === 'end' ? x - w : x;
  let out = '';
  if (outline) {
    const o = Math.max(1, scale / 3);
    for (const [dx, dy] of [[-o, 0], [o, 0], [0, -o], [0, o], [-o, -o], [o, o], [-o, o], [o, -o]]) {
      out += `<path d="${textPath(str, left + dx, y + dy, scale, gap)}" fill="${outline}"/>`;
    }
  }
  if (shadow) {
    const so = shadowOffset ?? Math.max(1, Math.round(scale * 0.6));
    out += `<path d="${textPath(str, left + so, y + so, scale, gap)}" fill="${shadow}"/>`;
  }
  out += `<path d="${textPath(str, left, y, scale, gap)}" fill="${fill}"/>`;
  return cls ? `<g class="${cls}">${out}</g>` : out;
}
