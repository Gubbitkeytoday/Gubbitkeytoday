// node scripts/build.mjs           → writes every card to dist/ and regenerates README.md
// node scripts/build.mjs preview   → same, plus preview/index.html laid out like the GitHub profile
import { mkdir, writeFile } from 'node:fs/promises';
import { profile } from './profile.mjs';
import { contributions, commitCalendar, repoList, summarize, emptyYear } from './lib/data.mjs';
import { esc } from './lib/ui.mjs';
import { board } from './cards/board.mjs';
import { ticket } from './cards/ticket.mjs';
import { map } from './cards/map.mjs';
import { station } from './cards/station.mjs';
import { ridership } from './cards/ridership.mjs';
import { endLine } from './cards/endline.mjs';

const root = new URL('../', import.meta.url);
const dist = new URL('dist/', root);

// Bangkok time decides what "today" is, whatever timezone the runner uses.
const now = new Date(Date.now() + 7 * 3600e3);
const today = now.toISOString().slice(0, 10);

let days;
let repos;
try {
  [days, repos] = await Promise.all([contributions(profile.user), repoList(profile.user)]);
  if (!days.some((d) => d.count)) {
    console.warn('contribution calendar is empty, counting commits in owned repos instead');
    days = await commitCalendar(days, repos);
  }
} catch (err) {
  if (process.env.CI) throw err;
  console.warn(`offline? using placeholder numbers (${err.message})`);
  days = emptyYear(today);
  repos = [];
}
const stats = summarize(days, today);
const ctx = { profile, date: now, today, days, stats, repos };

const cards = {
  'board.svg': board(ctx),
  'map.svg': map(ctx),
  'ridership.svg': ridership(ctx),
  'end-of-line.svg': endLine(ctx),
  ...Object.fromEntries(profile.tickets.map((t, i) => [`ticket-${t.id}.svg`, ticket(t, i)])),
  ...Object.fromEntries(profile.stations.map((s) => [`station-${s.code.toLowerCase()}.svg`, station(s, ctx)])),
};

await mkdir(dist, { recursive: true });
for (const [name, svg] of Object.entries(cards)) await writeFile(new URL(name, dist), svg);
console.log(`built ${Object.keys(cards).length} cards for ${today} · ${stats.thisYear} commits this year · ${repos.length} repos`);

const readme = renderReadme();
await writeFile(new URL('README.md', root), readme);

if (process.argv.includes('preview')) {
  const html = `<!doctype html><meta charset="utf-8"><title>profile preview</title>
<style>body{background:#0d1117;color:#e6edf3;font:14px system-ui;margin:0;padding:32px 16px}
main{max-width:860px;margin:auto;border:1px solid #30363d;border-radius:8px;padding:24px}
img{max-width:100%;vertical-align:top}a{color:#4493f8}</style>
<main>${readme.replace(/https:\/\/raw\.githubusercontent\.com\/[^/]+\/[^/]+\/output\//g, '../dist/').replace(/<!--[\s\S]*?-->/g, '')}</main>`;
  await mkdir(new URL('preview/', root), { recursive: true });
  await writeFile(new URL('preview/index.html', root), html);
  console.log('preview → preview/index.html');
}

function renderReadme() {
  const src = (file) => `https://raw.githubusercontent.com/${profile.user}/${profile.user}/${profile.repoBranch}/${file}`;
  const img = (file, alt, width) => `<img src="${src(file)}" alt="${esc(alt)}" width="${width}">`;
  const link = (href, inner) => `<a href="${esc(href)}">${inner}</a>`;

  const tickets = profile.tickets.map((t) => link(t.href, img(`ticket-${t.id}.svg`, `${t.from} — ${t.to}`, '24%'))).join(' ');
  const stations = [];
  for (let i = 0; i < profile.stations.length; i += 2) {
    stations.push(profile.stations.slice(i, i + 2).map((s) => {
      const href = s.live ?? `https://github.com/${profile.user}/${s.repo}`;
      return link(href, img(`station-${s.code.toLowerCase()}.svg`, `${s.code} ${s.name} — ${s.desc.join(' ')}`, '49%'));
    }).join(' '));
  }

  return `<!--
  Generated by scripts/build.mjs from scripts/profile.mjs — edit that file, not this one.
  .github/workflows/cards.yml redraws the cards daily and pushes them to the \`${profile.repoBranch}\` branch.
-->

<div align="center">

${img('board.svg', `${profile.board.name} — departure board with my latest pushes`, '100%')}

${tickets}

${img('map.svg', 'System map — my projects as stations on four lines: AI & MCP, Transit, Web & Play, Systems', '100%')}

${stations.join('\n\n')}

${img('ridership.svg', 'Ridership — commits, streaks and languages over the last 12 months', '100%')}

${img('end-of-line.svg', `${profile.endOfLine.title}. ${profile.endOfLine.quote}`, '100%')}

</div>
`;
}
